// Определяем, показывать ли подсказку
export function shouldShowTip(
  difficulty: "trainee" | "shift" | "peak",
  clientId: ClientId
): string | null {
  // Пик нагрузки — Лена молчит
  if (difficulty === "peak") return null;

  const tips = lennaTips[clientId];
  if (!tips || tips.length === 0) return null;

  // Стажёр — показывает все подсказки
  if (difficulty === "trainee") {
    const randomIndex = Math.floor(Math.random() * tips.length);
    return tips[randomIndex];
  }

  // Смена — показывает только 3 из 7 клиентов (~43% шанс)
  if (difficulty === "shift") {
    // Используем clientId как "seed" для стабильности
    const clientNumber = parseInt(clientId.replace("c", ""));
    const showFor = [1, 3, 5]; // Показываем для c1, c3, c5
    if (showFor.includes(clientNumber)) {
      const randomIndex = Math.floor(Math.random() * tips.length);
      return tips[randomIndex];
    }
    return null;
  }

  return null;
}